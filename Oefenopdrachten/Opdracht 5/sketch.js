function setup() {
  createCanvas(800, 400);


}

function draw() {
  background(220);

  push();
  fill("#0f0f0f");
  textSize(12);
  text("X: " + round(mouseX) + " | Y: " + round(mouseY), 710, 20);
  pop();

  // ========================================== //
  // 10 blokjes op een rij //
  // ========================================== //
  fill(0);
  text("1. ", 20, 15);
  for (let i = 0; i < 10; i++) {
    if (i == 6) {
      fill("blue");
    } else {
      fill("white");
    }
    rect(20 + i * 50, 30, 50, 50);
  }

  // ========================================== //
  // 5 blokjes onder elkaar //
  // ========================================== //
  fill(0);
  text("2. ", 20, 105);
  for (let i = 0; i < 5; i++) {
    fill(i * 255 / 4);
    rect(20, 120 + i * 50, 50, 50);
  }

  // ========================================== //
  // 4 blokjes naast elkaar //
  // ========================================== //
  fill(0);
  text("3. ", 80, 105);
  for (let i = 0; i < 4; i++) {
    fill(0, i * 255 / 3, 0);
    rect(80 + 25 * i * (i + 1) / 2, 120, 25 + i * 25, 50);
  }

  // ========================================== //
  // 4 blauwe blokjes naast elkaar //
  // ========================================== //
  fill(0);
  text("4. ", 80, 205);
  for (let i = 0; i < 4; i++) {
    fill(0, 0, 255 - i * 255 / 3);
    rect(80 + 25 * i * (i + 1) / 2, 220, 25 + i * 25, 50 + i * 25);
  }

  // ========================================== //
  // 6 cirkels naast elkaar //
  // ========================================== //
  text("5. ", 540, 25);
  push();
  fill(255);
  stroke(0);
  for (let i = 0; i < 6; i++) {
    strokeWeight(i * 2);
    circle(540 + i * 30, 40, 20);
  }
  pop();

  // ========================================== //
  // Bullseye //
  // ========================================== //
  fill(0);
  text("6. ", 350, 105);
  push();
  noStroke();
  for (let i = 0; i < 10; i++) {
    fill(i % 2 === 0 ? "red" : "white");
    circle(500, 235, 180 - i * 18);
  }
  pop();

  // ========================================== //
  // Accordeon //
  // ========================================== //  
  fill(0);
  text("7. ", 625, 105);
  push();
  stroke(100);
  strokeWeight(1);
  for (let i = 0; i < 21; i++) {
    let width = i < 12 ? 30 + i * (90 / 11) : 120 - (i - 11) * 10;
    fill(i % 2 === 0 ? 160 : 255);
    rect(625, 120 + i * 10, width, 10);
  }
  pop();
}
